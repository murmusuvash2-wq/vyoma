data class ApprovedBlueprint(
    val name: String,
    val goal: String,
    val screens: String,
    val data: String,
    val integrations: String,
    val permissions: String,
    val edgeCases: String,
    val acceptanceTests: String,
    val mcpTools: String = "GitHub MCP, SQLite/Room DB, Jetpack Navigation"
)

@Composable
internal fun BlueprintScreen(
    modifier: Modifier,
    initialIdea: String,
    onBack: () -> Unit,
    onApproved: (ApprovedBlueprint) -> Unit
) {
    var name by remember(initialIdea) { mutableStateOf(initialIdea.trim().take(32).ifBlank { "My Android app" }) }
    var goal by remember(initialIdea) { mutableStateOf(initialIdea.trim()) }
    var screens by remember(initialIdea) { mutableStateOf("Home, Details, Settings") }
    var data by remember(initialIdea) { mutableStateOf("Store the information the user creates; clarify what must remain on-device.") }
    var integrations by remember(initialIdea) { mutableStateOf("None specified yet") }
    var permissions by remember(initialIdea) { mutableStateOf("No special Android permissions unless a confirmed feature needs them.") }
    var edgeCases by remember(initialIdea) { mutableStateOf("Empty states, invalid input, offline use, and recoverable errors.") }
    var acceptanceTests by remember(initialIdea) { mutableStateOf("App opens; core flow works; invalid input is handled; data is not lost unexpectedly.") }
    var mcpTools by remember(initialIdea) { mutableStateOf("GitHub MCP, SQLite/Room DB, Jetpack Navigation") }

    Column(
        modifier = modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(horizontal = 18.dp, vertical = 14.dp),
        verticalArrangement = Arrangement.spacedBy(14.dp)
    ) {
        Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
            OutlinedButton(onClick = onBack, shape = RoundedCornerShape(12.dp)) {
                Icon(Icons.Default.ArrowBack, contentDescription = "Back")
                Spacer(Modifier.height(0.dp))
                Text("Back")
            }
        }
        Text("Blueprint review", color = Navy, fontSize = 29.sp, fontWeight = FontWeight.ExtraBold)
        Text("Edit the plan first. No code is generated by this screen.", color = Muted, fontSize = 13.sp, lineHeight = 19.sp)
        Card(colors = CardDefaults.cardColors(containerColor = Color.White), shape = RoundedCornerShape(20.dp)) {
            Column(Modifier.fillMaxWidth().padding(15.dp), verticalArrangement = Arrangement.spacedBy(7.dp)) {
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    Icon(Icons.Default.AutoAwesome, contentDescription = null, tint = Green)
                    Text("Draft · Android native", color = Green, fontWeight = FontWeight.Bold, fontSize = 13.sp)
                }
                Text("Target stack: Kotlin + Jetpack Compose + Material 3", color = Navy, fontSize = 12.sp)
            }
        }
        BlueprintField("Project name", name, { name = it }, "Short app name")
        BlueprintField("Goal and core problem", goal, { goal = it }, "What should this app help someone do?", minLines = 3)
        BlueprintField("Screens and navigation", screens, { screens = it }, "List the screens and how users move between them", minLines = 2)
        BlueprintField("Data to store", data, { data = it }, "What information does the app need?", minLines = 2)
        BlueprintField("MCP Tools & Integrations", mcpTools, { mcpTools = it }, "Model Context Protocol tools & services (e.g. GitHub MCP, SQLite DB)", minLines = 2)
        BlueprintField("Integrations", integrations, { integrations = it }, "APIs, sign-in, maps, payments, or none", minLines = 2)
        BlueprintField("Android permissions", permissions, { permissions = it }, "Only permissions justified by a feature", minLines = 2)
        BlueprintField("Edge cases and errors", edgeCases, { edgeCases = it }, "Offline, empty data, invalid input, recovery", minLines = 2)
        BlueprintField("Acceptance checks", acceptanceTests, { acceptanceTests = it }, "How will we know the first version works?", minLines = 2)
        Surface(color = Color(0xFFEAF5EE), shape = RoundedCornerShape(16.dp)) {
            Text(
                "Approval saves this blueprint as a local draft in this prototype. It does not generate code, call an AI service, or sync to GitHub.",
                modifier = Modifier.padding(14.dp), color = Green, fontSize = 12.sp, lineHeight = 18.sp
            )
        }
        Button(
            onClick = {
                onApproved(ApprovedBlueprint(name.trim(), goal.trim(), screens.trim(), data.trim(), integrations.trim(), permissions.trim(), edgeCases.trim(), acceptanceTests.trim(), mcpTools.trim()))
            },
            enabled = name.isNotBlank() && goal.isNotBlank(),
            modifier = Modifier.fillMaxWidth().height(54.dp),
            shape = RoundedCornerShape(16.dp),
            colors = ButtonDefaults.buttonColors(containerColor = Navy)
        ) {
            Text("Approve blueprint", fontWeight = FontWeight.Bold)
        }
        Text("You can still revise the plan before any future code-generation step.", color = Muted, fontSize = 11.sp)
    }
}

@Composable
private fun BlueprintField(
    label: String,
    value: String,
    onValueChange: (String) -> Unit,
    placeholder: String,
    minLines: Int = 1
) {
    Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
        Text(label, color = Navy, fontWeight = FontWeight.SemiBold, fontSize = 13.sp)
        OutlinedTextField(
            value = value,
            onValueChange = onValueChange,
            modifier = Modifier.fillMaxWidth(),
            placeholder = { Text(placeholder, fontSize = 12.sp) },
            minLines = minLines,
            shape = RoundedCornerShape(15.dp),
            colors = androidx.compose.material3.OutlinedTextFieldDefaults.colors(
                focusedBorderColor = Green,
                unfocusedBorderColor = Line
            )
        )
    }
}
